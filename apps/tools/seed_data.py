def _split(text):
    return [part.strip() for part in text.split("|") if part.strip()]


def build_tools():
    """Return the tools as dicts ready for Tool.objects.update_or_create().

    The list is re-ordered so tools from different categories are interleaved; this makes the
    "recently added" section on the homepage show a mix of categories.
    """
    per_category = {}
    rows = []
    for name, cat, url, pricing, tagline, desc, feats, pros, cons, uses, platforms, flags in _RAW:
        rank = per_category.get(cat, 0)
        per_category[cat] = rank + 1
        pros_list, cons_list = _split(pros), _split(cons)
        if pricing in ("free", "freemium"):
            pros_list.append("Free to try" if pricing == "freemium" else "No payment needed")
        if pricing == "freemium":
            cons_list.append("Advanced features need a paid plan")
        if pricing == "paid":
            cons_list.append("No free plan - check the site for any trial")
        note = {
            "free": "Listed as free to use. Check the official site for current terms.",
            "freemium": "Has a free plan and paid upgrades. Check the official site for current plans and limits.",
            "paid": "Paid service. Check the official site for current plans and any trial.",
        }[pricing]
        rows.append((rank, {
            "name": name, "category": cat, "website_url": url, "pricing_model": pricing, "pricing_note": note,
            "tagline": tagline, "description": desc, "features": "\n".join(_split(feats)),
            "pros": "\n".join(pros_list), "cons": "\n".join(cons_list), "use_cases": "\n".join(_split(uses)),
            "platforms": platforms, "is_open_source": flags.get("open_source", False),
            "is_featured": flags.get("featured", False), "is_trending": flags.get("trending", False),
        }))
    rows.sort(key=lambda item: item[0])  # first tool of every category, then the second, ...
    return [row for _rank, row in rows]
